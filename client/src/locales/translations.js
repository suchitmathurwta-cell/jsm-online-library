export function getLocalizedLanguage(languageRaw, lang = 'hi') {
  if (!languageRaw) return lang === 'hi' ? 'हिंदी' : (lang === 'ur' ? 'اردو' : 'Hindi');
  
  const lower = languageRaw.toLowerCase();
  if (lower.includes('hindi') && lower.includes('urdu')) {
    if (lang === 'hi') return 'हिंदी / उर्दू (द्विभाषी)';
    if (lang === 'ur') return 'ہندی / اردو (دو لسانی)';
    return 'Hindi & Urdu (Bilingual)';
  }
  if (lower.includes('hindi')) {
    if (lang === 'hi') return 'हिंदी (देवनागरी)';
    if (lang === 'ur') return 'ہندی (دیوناگری)';
    return 'Hindi';
  }
  if (lower.includes('urdu')) {
    if (lang === 'hi') return 'उर्दू (नस्तलीक़)';
    if (lang === 'ur') return 'اردو (نستعلیق)';
    return 'Urdu';
  }
  if (lower.includes('sanskrit')) {
    if (lang === 'hi') return 'संस्कृत';
    if (lang === 'ur') return 'سنسکرت';
    return 'Sanskrit';
  }
  if (lower.includes('english')) {
    if (lang === 'hi') return 'अंग्रेज़ी';
    if (lang === 'ur') return 'انگریزی';
    return 'English';
  }
  
  if (languageRaw.includes('/')) {
    const parts = languageRaw.split('/');
    if (lang === 'hi') return parts[0]?.trim();
    if (lang === 'ur') return parts[parts.length - 1]?.trim();
    return parts[1]?.trim() || parts[0]?.trim();
  }

  return languageRaw;
}
